//! Static-site renderer: turns doc IR plus module maps into a
//! self-contained HTML tree (no server, no external requests).
//!
//! The site is a set of language *trees* (`cpp/`, `c/`, `py/`), each with
//! its own module hierarchy and pages, sharing one search index and one
//! landing page. All Markdown and signature text is pre-rendered in Rust
//! into view models; the embedded minijinja templates only do layout.

